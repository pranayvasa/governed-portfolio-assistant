"""Render web/index.html and web/persona.js from persona.json.

persona.json is the one place that names the person the assistant is about:
name, LinkedIn, pronouns, page text and suggested questions. The Python code
reads it directly; the static page is rendered from it here, so the page works
without JavaScript and needs no build step on Vercel.

    python scripts/render_web.py           # write web/index.html and web/persona.js
    python scripts/render_web.py --check   # exit 1 if they are out of date
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = Path(__file__).resolve().parent / "templates" / "index.html"

ICONS = {
    "chart": '<path d="M4 19h16M7 16V9M12 16V5M17 16v-4"/>',
    "trend": '<path d="M4 17l5-5 4 4 7-8"/><path d="M15 8h5v5"/>',
    "clock": '<circle cx="12" cy="12" r="8"/><path d="M12 8v4l3 2"/>',
    "star": '<path d="M12 3l2.5 5.5L20 9l-4 4 1 6-5-3-5 3 1-6-4-4 5.5-.5z"/>',
}


def esc(text: str) -> str:
    # Apostrophes stay as they are: every attribute in the template is double-quoted.
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def render(root: Path) -> dict[Path, str]:
    """Rendered files for the persona.json in `root`, keyed by output path."""
    p = json.loads((root / "persona.json").read_text())
    starters = "".join(
        f'      <button type="button" class="starter" data-q="{esc(s["question"])}">\n'
        f'        <svg viewBox="0 0 24 24" aria-hidden="true">{ICONS[s["icon"]]}</svg>\n'
        f'        <span>{esc(s["label"])}</span>\n'
        "      </button>\n"
        for s in p["starters"]
    )
    # Optional footer credit, e.g. who built a demo persona's page.
    credit = p.get("credit")
    credit_html = (
        f'    <span class="credit"><a href="{esc(credit["url"])}" target="_blank" rel="noopener">{esc(credit["text"])}</a></span>\n'
        if credit else ""
    )
    values = {
        "page_title": p["page"]["title"],
        "page_description": p["page"]["description"],
        "tagline": p["page"]["tagline"],
        "name": p["name"],
        "short_name": p["short_name"],
        "initials": p["initials"],
        "possessive": p["pronouns"]["possessive"],
        "linkedin_url": p["linkedin_url"],
    }
    html = TEMPLATE.read_text().replace("{{starters}}", starters).replace("{{credit}}", credit_html)
    for key, value in values.items():
        html = html.replace("{{" + key + "}}", esc(value))
    if "{{" in html:
        raise ValueError("unfilled placeholder in scripts/templates/index.html")
    js = (
        "// Generated by scripts/render_web.py from persona.json. Don't edit by hand.\n"
        f"window.PERSONA = {json.dumps(p, ensure_ascii=False, indent=2)};\n"
    )
    return {root / "web" / "index.html": html, root / "web" / "persona.js": js}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the rendered files are out of date")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root to render (default: this one)")
    args = parser.parse_args()

    stale = []
    for path, text in render(args.root).items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not args.check:
                path.write_text(text)
    if args.check and stale:
        print("Out of date: " + ", ".join(str(p.relative_to(args.root)) for p in stale))
        sys.exit(1)
    if not args.check:
        print("rendered web/index.html and web/persona.js" if stale else "already up to date")


if __name__ == "__main__":
    main()
